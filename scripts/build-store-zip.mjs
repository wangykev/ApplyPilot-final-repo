#!/usr/bin/env node
/**
 * Builds the reviewable Chrome Web Store package into dist/.
 *
 *   node scripts/build-store-zip.mjs                 # build at the pinned STORE_VERSION
 *   node scripts/build-store-zip.mjs --version 1.0.1 # override the version
 *   node scripts/build-store-zip.mjs --keep-key      # keep manifest.key (see below)
 *   node scripts/build-store-zip.mjs --dry           # print the plan, write nothing
 *
 * WHY A SCRIPT AND NOT A HAND-EDITED manifest.production.json
 * -----------------------------------------------------------
 * Two manifests drift. The dev manifest is the one that gets edited during a debugging
 * round (a host added, a permission tried), and a hand-maintained twin silently keeps the
 * old shape until a reviewer finds the difference. So there is ONE manifest and a
 * declared set of transforms applied to a copy at package time.
 *
 * THE FILE LIST IS AN ALLOWLIST, AND THAT IS THE LOAD-BEARING PART
 * ---------------------------------------------------------------
 * `data/` is gitignored deny-by-default because it holds the operator's REAL profile
 * (name, address, phone, demographics) and a real credentials file. A denylist would ship
 * every one of those the day someone adds a file it does not name. So nothing is copied
 * unless it appears in SHIP_FILES / SHIP_DIR_ALLOW below, and a data file that is not
 * explicitly allow-listed is a HARD FAILURE rather than a silent skip — publishing a
 * public extension carrying your own PII is not a recoverable mistake.
 */

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");
const STAGE = path.join(DIST, "applypilot");

/** The version that goes to the store. Bump this, not manifest.json's 0.0.1 dev value. */
const STORE_VERSION = "1.0.0";
const STORE_NAME = "ApplyPilot";
/** Manifest description: Chrome caps this at 132 characters. */
const STORE_DESCRIPTION =
  "Fills job application forms from your saved profile, flags every guess for your review, and never submits without you.";

/** Origins that exist only for local development and must not ship. */
const DEV_ORIGINS = [/^https?:\/\/localhost(?::\d+)?\//i, /^https?:\/\/127\.0\.0\.1(?::\d+)?\//i];

/** Every file that ships, named individually. */
const SHIP_FILES = [
  "manifest.json",
  "background.js",
  "ats.js",
  "cdp.js",
  "db.js",
  "discover.js",
  "fill-driver.js",
  "gmail.js",
  "lib.js",
  "llm-keys.js",
  "llm.js",
  "popup.html",
  "popup.js",
  "summary-lib.js",
  "summary.html",
  "summary.js",
];

/**
 * Directories that may contribute files, with an explicit per-directory allowlist.
 * `null` would mean "everything in it" — deliberately unsupported, so no directory can
 * quietly grow a shipped file.
 */
const SHIP_DIR_ALLOW = {
  data: [
    // Built-in fallback answers (the date_day default etc). No personal data.
    "application_defaults.json",
    // The question-mapping rulebook the engine reads. No personal data.
    "question_mapping_schema.json",
  ],
  // Generated by scripts/build-icons.mjs. icon128 is also the store's required 128×128.
  icons: ["icon16.png", "icon32.png", "icon48.png", "icon128.png"],
};

/**
 * Anything matching this in a shipped data file is treated as leaked PII and fails the
 * build. Cheap, and it has one job: catch the case where a real profile.json was copied
 * over an allow-listed filename.
 */
const PII_SHAPES = [
  { name: "email address", re: /[\w.+-]+@[\w-]+\.[\w.]{2,}/ },
  { name: "US phone number", re: /\b\d{3}[-.\s]\d{3}[-.\s]\d{4}\b/ },
  { name: "password field", re: /"password"\s*:\s*"[^"]+"/i },
  { name: "street address", re: /\b\d{1,5}\s+\w+(\s+\w+)*\s+(st|street|ave|avenue|rd|road|blvd|dr|drive|ln|lane|way|ct|court)\b/i },
];

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(`--${name}`);
const optValue = (name) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : null;
};

const DRY = flag("dry");
const KEEP_KEY = flag("keep-key");
const VERSION = optValue("version") || STORE_VERSION;

const problems = [];
const notes = [];

function fail(msg) {
  problems.push(msg);
}

// --------------------------------------------------------------- manifest transform
const rawManifest = fs.readFileSync(path.join(ROOT, "manifest.json"), "utf8");
const manifest = JSON.parse(rawManifest);

if (!/^\d+(\.\d+){0,3}$/.test(VERSION)) {
  fail(`--version "${VERSION}" is not a valid Chrome version (1-4 dot-separated integers).`);
}

manifest.name = STORE_NAME;
manifest.version = VERSION;
manifest.description = STORE_DESCRIPTION;

if (STORE_DESCRIPTION.length > 132) {
  fail(`STORE_DESCRIPTION is ${STORE_DESCRIPTION.length} chars; Chrome's limit is 132.`);
}

/**
 * `key` pins the extension ID for UNPACKED loads so the dev build keeps a stable ID for
 * its Gmail OAuth client (docs/gmail-setup.md §1). The store mints its OWN key and
 * derives the published ID from that, so shipping ours is at best ignored and at worst a
 * rejected upload — and the published ID will differ from the dev one regardless.
 *
 * ⚠ CONSEQUENCE, and it is the thing most likely to bite after approval: the Gmail OAuth
 * client is registered against a SPECIFIC extension ID. Publishing changes the ID, so
 * chrome.identity.getAuthToken fails on the store build until a Chrome-Extension OAuth
 * client is registered for the PUBLISHED id and pasted into oauth2.client_id.
 */
if (!KEEP_KEY) {
  if (manifest.key) {
    delete manifest.key;
    notes.push(
      "Stripped manifest.key — the store derives the published ID from its own key.\n" +
        "     ⚠ After the item is created, register a Chrome-Extension OAuth client for the\n" +
        "       PUBLISHED extension ID and update oauth2.client_id, or Gmail auto-verify will\n" +
        "       fail on the store build only.",
    );
  }
} else {
  notes.push("Kept manifest.key (--keep-key). Only correct if it is the STORE item's own public key.");
}

// Strip localhost from host_permissions.
const beforeHosts = manifest.host_permissions ?? [];
manifest.host_permissions = beforeHosts.filter(
  (h) => !DEV_ORIGINS.some((re) => re.test(h)),
);
const droppedHosts = beforeHosts.filter((h) => !manifest.host_permissions.includes(h));
if (droppedHosts.length) notes.push(`Dropped dev host_permissions: ${droppedHosts.join(", ")}`);

// Strip localhost from externally_connectable, and drop the key entirely if nothing is left.
if (manifest.externally_connectable?.matches) {
  const before = manifest.externally_connectable.matches;
  const kept = before.filter((m) => !DEV_ORIGINS.some((re) => re.test(m)));
  const dropped = before.filter((m) => !kept.includes(m));
  if (dropped.length) notes.push(`Dropped dev externally_connectable: ${dropped.join(", ")}`);
  if (kept.length) {
    manifest.externally_connectable.matches = kept;
  } else {
    delete manifest.externally_connectable;
    notes.push("Removed externally_connectable entirely — no production origins remained.");
  }
}

// A production build that can still be driven from localhost defeats the point of the strip.
const leftoverDev = JSON.stringify(manifest).match(/localhost|127\.0\.0\.1/gi);
if (leftoverDev) fail(`Dev origin still present in the built manifest: ${[...new Set(leftoverDev)].join(", ")}`);

if (!manifest.host_permissions.some((h) => h.startsWith("https://"))) {
  fail("No https host_permissions left — the site handoff origin was stripped too.");
}

// ------------------------------------------------------------------- collect files
const staged = []; // { from, to, bytes }

for (const rel of SHIP_FILES) {
  const from = path.join(ROOT, rel);
  if (!fs.existsSync(from)) {
    fail(`SHIP_FILES names "${rel}" but it does not exist.`);
    continue;
  }
  staged.push({ from, to: rel, bytes: fs.statSync(from).size });
}

for (const [dir, allowed] of Object.entries(SHIP_DIR_ALLOW)) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) {
    fail(`SHIP_DIR_ALLOW names "${dir}/" but it does not exist.`);
    continue;
  }
  const present = fs.readdirSync(abs).filter((f) => fs.statSync(path.join(abs, f)).isFile());

  for (const name of allowed) {
    if (!present.includes(name)) {
      fail(`SHIP_DIR_ALLOW["${dir}"] names "${name}" but it is missing.`);
      continue;
    }
    const from = path.join(abs, name);
    // Text only. Decoding a PNG as UTF-8 and running prose regexes over the result is
    // meaningless, and a phone-shaped run of bytes in compressed image data would fail the
    // build for nothing. PII hides in text; binary assets are checked by eye.
    if (/\.(json|txt|js|css|html|md)$/i.test(name)) {
      const body = fs.readFileSync(from, "utf8");
      for (const { name: shape, re } of PII_SHAPES) {
        if (re.test(body)) {
          fail(
            `${dir}/${name} looks like it contains a real ${shape}. ` +
              `Shipped data files must hold no personal data — refusing to package it.`,
          );
        }
      }
    }
    staged.push({ from, to: `${dir}/${name}`, bytes: fs.statSync(from).size });
  }

  // Everything else in the directory is reported, so a new file is a decision, not an accident.
  const skipped = present.filter((f) => !allowed.includes(f));
  if (skipped.length) notes.push(`Not shipped from ${dir}/ (not allow-listed): ${skipped.join(", ")}`);
}

// ------------------------------------------------------------------------- report
const totalBytes = staged.reduce((n, f) => n + f.bytes, 0) + Buffer.byteLength(JSON.stringify(manifest));
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

console.log(`\nApplyPilot → Chrome Web Store package`);
console.log(`  name        ${manifest.name}`);
console.log(`  version     ${manifest.version}   (dev manifest says ${JSON.parse(rawManifest).version})`);
console.log(`  files       ${staged.length}  (${kb(totalBytes)} unzipped)`);
console.log(`  permissions ${(manifest.permissions ?? []).join(", ")}`);
console.log(`  hosts       ${manifest.host_permissions.length}`);
for (const h of manifest.host_permissions) console.log(`              ${h}`);

if (notes.length) {
  console.log(`\n  Notes`);
  for (const n of notes) console.log(`   • ${n}`);
}

if (problems.length) {
  console.error(`\n  ✖ ${problems.length} problem(s) — nothing was written:`);
  for (const p of problems) console.error(`   • ${p}`);
  process.exit(1);
}

if (DRY) {
  console.log(`\n  --dry: no files written.\n`);
  process.exit(0);
}

// -------------------------------------------------------------------------- write
fs.rmSync(STAGE, { recursive: true, force: true });
fs.mkdirSync(STAGE, { recursive: true });

for (const f of staged) {
  if (f.to === "manifest.json") continue; // written from the transformed object below
  const dest = path.join(STAGE, f.to);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(f.from, dest);
}
fs.writeFileSync(path.join(STAGE, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

const zipName = `applypilot-${manifest.version}.zip`;
const zipPath = path.join(DIST, zipName);
fs.rmSync(zipPath, { force: true });

try {
  writeZip(zipPath, staged.map((f) => f.to));
} catch (err) {
  console.error(`\n  ✖ Could not create the zip: ${err.message}`);
  console.error(`    The staged folder is ready at ${STAGE} — zip its CONTENTS by hand`);
  console.error(`    (manifest.json must sit at the zip root, not inside a subfolder).`);
  process.exit(1);
}

const zipBytes = fs.statSync(zipPath).size;
const sha = createHash("sha256").update(fs.readFileSync(zipPath)).digest("hex");

console.log(`\n  ✔ ${path.relative(ROOT, zipPath)}  (${kb(zipBytes)})`);
console.log(`    sha256 ${sha}`);
console.log(`    staged ${path.relative(ROOT, STAGE)}  — load this unpacked to test the exact build\n`);

// ===================================================================== zip writer
//
// WHY THIS IS HAND-ROLLED INSTEAD OF SHELLING OUT
// -----------------------------------------------
// The first version called PowerShell's Compress-Archive on Windows and `zip` elsewhere.
// Both are wrong here:
//
//   • Windows PowerShell 5.1's Compress-Archive writes entry names with BACKSLASH
//     separators ("data\application_defaults.json"). The ZIP spec (APPNOTE 4.4.17.1)
//     requires forward slashes, so that is not a path — it is a file whose NAME contains
//     a backslash. Chrome then cannot resolve data/application_defaults.json and the
//     engine loses its defaults, with nothing in the build output to say why. Verified
//     against this repo, which is what prompted the rewrite.
//   • `zip` and `pwsh` are simply absent on this machine, so the fallback was unreachable.
//
// zlib is in Node's stdlib, the format is a few dozen bytes of header, and doing it here
// makes the artifact DETERMINISTIC (fixed timestamps ⇒ identical bytes for identical
// input, so the printed sha256 is worth something as a "did anything change?" check).

/**
 * Built on FIRST USE, and `var` rather than `const`, deliberately.
 *
 * `writeZip` is called from the main flow ABOVE this point, which works because function
 * declarations hoist — but a module-level `const` does not initialise until control
 * reaches it, so referencing one from an earlier call throws "Cannot access before
 * initialization" (its temporal dead zone). `var` hoists to `undefined`, which doubles as
 * the "not built yet" sentinel. Keeping the writer at the bottom keeps the readable build
 * narrative at the top of the file.
 */
var crcTable;

function crc32(buf) {
  if (!crcTable) {
    crcTable = new Int32Array(256);
    for (let i = 0; i < 256; i++) {
      let c = i;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[i] = c;
    }
  }
  let c = ~0;
  for (let i = 0; i < buf.length; i++) c = crcTable[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return ~c >>> 0;
}

/** Write `names` (read from STAGE, forward-slashed) as a deflated zip at `outPath`. */
function writeZip(outPath, names) {
  /**
   * Fixed MS-DOS timestamp (2026-08-19 12:00:00). Real mtimes would change the zip's bytes
   * on every checkout, which defeats the printed sha256 as a change signal — and a store
   * package has no use for per-file times. Function-scoped for the same TDZ reason above.
   */
  const DOS_TIME = (12 << 11) | (0 << 5) | 0;
  const DOS_DATE = ((2026 - 1980) << 9) | (8 << 5) | 19;

  const chunks = [];
  const central = [];
  let offset = 0;

  for (const rel of names) {
    const name = rel.split(path.sep).join("/");
    const nameBuf = Buffer.from(name, "utf8");
    const raw = fs.readFileSync(path.join(STAGE, rel));
    const deflated = zlib.deflateRawSync(raw, { level: 9 });
    const crc = crc32(raw);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); // local file header signature
    local.writeUInt16LE(20, 4); // version needed to extract (2.0)
    local.writeUInt16LE(0, 6); // general purpose flags
    local.writeUInt16LE(8, 8); // method: deflate
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(deflated.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28); // extra field length
    chunks.push(local, nameBuf, deflated);

    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0); // central directory header signature
    cd.writeUInt16LE(0x031e, 4); // version made by: UNIX, 3.0
    cd.writeUInt16LE(20, 6);
    cd.writeUInt16LE(0, 8);
    cd.writeUInt16LE(8, 10);
    cd.writeUInt16LE(DOS_TIME, 12);
    cd.writeUInt16LE(DOS_DATE, 14);
    cd.writeUInt32LE(crc, 16);
    cd.writeUInt32LE(deflated.length, 20);
    cd.writeUInt32LE(raw.length, 24);
    cd.writeUInt16LE(nameBuf.length, 28);
    cd.writeUInt16LE(0, 30); // extra
    cd.writeUInt16LE(0, 32); // comment
    cd.writeUInt16LE(0, 34); // disk number start
    cd.writeUInt16LE(0, 36); // internal attributes
    cd.writeUInt32LE((0o100644 << 16) >>> 0, 38); // external: regular file, rw-r--r--
    cd.writeUInt32LE(offset, 42); // offset of the local header
    central.push(cd, nameBuf);

    offset += local.length + nameBuf.length + deflated.length;
  }

  const cdBuf = Buffer.concat(central);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0); // end of central directory signature
  eocd.writeUInt16LE(0, 4); // this disk
  eocd.writeUInt16LE(0, 6); // disk with the central directory
  eocd.writeUInt16LE(names.length, 8);
  eocd.writeUInt16LE(names.length, 10);
  eocd.writeUInt32LE(cdBuf.length, 12);
  eocd.writeUInt32LE(offset, 16);
  eocd.writeUInt16LE(0, 20); // comment length

  fs.writeFileSync(outPath, Buffer.concat([...chunks, cdBuf, eocd]));
}
