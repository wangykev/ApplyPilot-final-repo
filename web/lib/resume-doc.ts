import type { Profile } from "@/lib/profile-schema";
import type { TailoredResume } from "@/lib/tailor";

/**
 * Render a TailoredResume into the two downloadable documents:
 *  - a .tex file in the operator's sb2nov / Jake Gutierrez template (compile in
 *    Overleaf / any pdfLaTeX for the exact resume look), and
 *  - a standalone print-ready HTML document (opened in a new window →
 *    "Save as PDF" in the print dialog) — single-column, standard headings,
 *    selectable text: the ATS-safe layout, zero extra dependencies.
 *
 * Pure string builders — no DOM, no IO — so both are unit-testable.
 */

// ── shared model ─────────────────────────────────────────────────────────────

export type ResumeHeader = {
  name: string;
  phone: string;
  email: string;
  links: { label: string; url: string }[];
};

export function headerFromProfile(profile: Profile): ResumeHeader {
  const pi = profile.personal_info;
  const links = (profile.websites ?? [])
    .filter((w) => w.url && w.url.trim())
    .map((w) => {
      const url = w.url.trim();
      const label = url.replace(/^https?:\/\//, "").replace(/\/$/, "");
      return { label, url: /^https?:\/\//.test(url) ? url : "https://" + url };
    });
  return {
    name: [pi.first_name, pi.last_name].filter(Boolean).join(" "),
    phone: pi.phone_number || "",
    email: pi.email || "",
    links,
  };
}

const MONTHS = ["Jan.", "Feb.", "Mar.", "Apr.", "May", "Jun.", "Jul.", "Aug.", "Sep.", "Oct.", "Nov.", "Dec."];

/** "2025-05" → "May 2025"; "2025" → "2025"; "" → "". */
export function displayDate(d: string): string {
  const m = String(d || "").match(/^(\d{4})-(\d{2})$/);
  if (m) {
    const n = Number(m[2]);
    return n >= 1 && n <= 12 ? `${MONTHS[n - 1]} ${m[1]}` : m[1];
  }
  return String(d || "");
}

export function dateRange(from: string, to: string, current: boolean): string {
  const a = displayDate(from);
  const b = current ? "Present" : displayDate(to);
  return [a, b].filter(Boolean).join(" – ");
}

// ── LaTeX ────────────────────────────────────────────────────────────────────

/** Escape LaTeX specials in ONE pass — replacements are never rescanned, so the
 *  braces inserted by \textbackslash{} can't get double-escaped. */
export function escapeLatex(s: string): string {
  return String(s ?? "").replace(/[\\&%$#_{}~^]/g, (ch) => {
    if (ch === "\\") return "\\textbackslash{}";
    if (ch === "~") return "\\textasciitilde{}";
    if (ch === "^") return "\\textasciicircum{}";
    return "\\" + ch;
  });
}

/** The sb2nov / Jake Gutierrez preamble (verbatim from data/resume.tex — the
 *  operator's template). Single column by construction; \pdfgentounicode keeps
 *  the PDF machine-readable. */
